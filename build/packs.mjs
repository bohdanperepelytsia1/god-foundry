const folders = {}
const folder = (name, color, sort) => {
  const _id = id('folder:' + name)
  folders[name] = { _id, _key: `!folders!${_id}`, name, type: 'Item', folder: null, sorting: 'a', sort, color, description: '', flags: {} }
  return _id
}
